const norm = (s?: string | null) => (s ?? "").trim().toLowerCase();

/** Free-text country → short token used in the tables above. */
function countryToken(country: string): string {
  if (!country) return "";
  if (/(^|\b)(usa|us|u\.s|united states|america)(\b|$)/.test(country)) return "us";
  if (/(united kingdom|uk|england|scotland|wales|great britain)/.test(country)) return "uk";
  return country;
}

/**
 * Best-effort coordinates for a venue location. Undefined when nothing in
 * the tables matches — callers should just skip the map dot.
 */
export function locate(
  city?: string | null,
  region?: string | null,
  country?: string | null,
): GeoPoint | undefined {
  const c = norm(city);
  const cc = countryToken(norm(country));
  if (c) {
    const hit = CITIES[cc ? `${c},${cc}` : ""] ?? CITIES[c];
    if (hit) return hit;
  }
  const r = norm(region);
  if (r && (cc === "us" || cc === "")) {
    const state = US_STATES[r];
    if (state) return state;
  }
  return COUNTRIES[cc] ?? undefined;
}
